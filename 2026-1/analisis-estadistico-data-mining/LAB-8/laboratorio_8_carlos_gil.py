# Imputación para variables numéricas con la mediana
datos["ingreso_mensual"] = datos["ingreso_mensual"].fillna(datos["ingreso_mensual"].median())
datos["gasto_promedio"] = datos["gasto_promedio"].fillna(datos["gasto_promedio"].median())

# Imputación para variables categóricas con la moda
datos["canal_compra"] = datos["canal_compra"].fillna(datos["canal_compra"].mode()[0])
datos["satisfaccion"] = datos["satisfaccion"].fillna(datos["satisfaccion"].mode()[0])

print("\nValores faltantes después de la imputación:")
print(datos.isnull().sum())

# ============================================================
# 7. DETECCIÓN Y TRATAMIENTO DE VALORES ATÍPICOS
# ============================================================

# Se analizó la variable gasto_promedio mediante un boxplot para identificar
# posibles valores atípicos que pudieran distorsionar los resultados
# estadísticos y los modelos posteriores.

# Para detectar outliers se utilizó el método del rango intercuartílico (IQR),
# que considera como atípicos aquellos valores que se encuentran por debajo
# de Q1 - 1.5 * IQR o por encima de Q3 + 1.5 * IQR.

# El procedimiento permitió identificar un valor extremo en la variable
# gasto_promedio que se encontraba fuera de los límites aceptables de la
# distribución de los datos.

# Debido a que este valor no representaba el comportamiento normal de los
# clientes y podía afectar la media, la desviación estándar y los modelos
# predictivos, se decidió corregirlo.

# En lugar de eliminar el registro, el valor atípico fue reemplazado por la
# mediana de los gastos válidos. La mediana es una medida robusta que no se
# ve afectada por valores extremos y permite conservar el registro dentro
# del conjunto de datos.

# Finalmente, se generó un segundo boxplot para verificar que la variable
# gasto_promedio ya no presentara valores atípicos significativos y que la
# distribución fuera más representativa del comportamiento real de los clientes.

# Se analiza la variable gasto_promedio porque contiene un valor extremo

plt.figure(figsize=(8, 4))
sns.boxplot(x=datos["gasto_promedio"])
plt.title("Boxplot de gasto promedio antes de tratar outliers")
