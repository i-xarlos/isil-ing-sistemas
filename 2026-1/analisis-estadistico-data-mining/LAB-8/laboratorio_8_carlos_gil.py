# ============================================================
# 16. CLUSTERING: SEGMENTACIÓN DE CLIENTES CON K-MEANS
# ============================================================

# En esta etapa se realiza una segmentación no supervisada
# de los clientes utilizando el algoritmo K-Means.

# ------------------------------------------------------------
# ¿Qué es K-Means?
# ------------------------------------------------------------

# K-Means es un algoritmo de clustering que agrupa observaciones
# en K grupos (clusters) según su similitud.

# Los clientes dentro de un mismo cluster comparten características
# similares en términos de comportamiento o valor.

# ------------------------------------------------------------
# Selección de variables
# ------------------------------------------------------------

# Se eligen variables relacionadas con el valor comercial del cliente:
# - ingreso_mensual: capacidad económica
# - frecuencia_compra: comportamiento de compra
# - gasto_promedio: nivel de consumo
# - satisfaccion_codificada: percepción del cliente

variables_cluster = [
    "ingreso_mensual",
    "frecuencia_compra",
    "gasto_promedio",
    "satisfaccion_codificada"
]

X_cluster = datos_transformados[variables_cluster]

# ------------------------------------------------------------
# Normalización de variables
# ------------------------------------------------------------

# Se aplica StandardScaler para asegurar que todas las variables
# tengan la misma escala y ninguna domine el cálculo de distancias.

escalador_cluster = StandardScaler()
X_cluster_escalado = escalador_cluster.fit_transform(X_cluster)

# ------------------------------------------------------------
# Entrenamiento del modelo K-Means
# ------------------------------------------------------------

# Se define el número de clusters (k=3), representando:
# - Clientes de bajo valor
# - Clientes de valor medio
# - Clientes de alto valor

kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)

# Se ajusta el modelo y se asigna cada cliente a un cluster
datos_transformados["cluster"] = kmeans.fit_predict(X_cluster_escalado)

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# Cada cliente queda asignado a un grupo (0, 1 o 2),
# lo que permite realizar segmentación de mercado.

# Esta segmentación puede utilizarse para:
# - Personalización de campañas de marketing
# - Estrategias de fidelización
# - Identificación de clientes de alto valor

print("\nClientes con cluster asignado:")
print(
    datos_transformados[
        [
            "cliente_id",
            "ingreso_mensual",
            "frecuencia_compra",
            "gasto_promedio",
            "satisfaccion_codificada",
            "cluster"
        ]
    ].head()
)

# ============================================================
# 17. EVALUACIÓN DEL CLUSTERING
# ============================================================

# En esta etapa se evalúa la calidad de la segmentación
# realizada con el algoritmo K-Means.

# ------------------------------------------------------------
# Métrica utilizada: Silhouette Score
# ------------------------------------------------------------

# El coeficiente de Silhouette mide qué tan bien están separados
# los clusters y qué tan cohesionados son internamente.

# Su interpretación es la siguiente:
# - Cerca de 1  → clusters bien separados y bien definidos
# - Cerca de 0  → clusters superpuestos o poco diferenciados
# - Menor a 0  → mala asignación de clusters

# ------------------------------------------------------------
# Cálculo del Silhouette Score
# ------------------------------------------------------------

silhouette = silhouette_score(X_cluster_escalado, datos_transformados["cluster"])

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

print("\nCoeficiente Silhouette:")
print(round(silhouette, 3))

# ------------------------------------------------------------
# INTERPRETACIÓN
# ------------------------------------------------------------

# Un valor bajo de silhouette indica que los clusters no están
# claramente separados, lo que sugiere que:
# - Las variables pueden no ser suficientes para segmentar bien
# - O el valor de K (3 clusters) puede no ser el óptimo

# En este caso, el resultado debe interpretarse como una segmentación
# exploratoria más que como una división perfectamente definida.

# Esto significa que los clusters son útiles para análisis inicial,
# pero requieren validación adicional antes de usarse en decisiones críticas.

