plt.show()

# Método IQR para detectar valores atípicos

Q1 = datos["gasto_promedio"].quantile(0.25)
Q3 = datos["gasto_promedio"].quantile(0.75)
IQR = Q3 - Q1

limite_inferior = Q1 - 1.5 * IQR
limite_superior = Q3 + 1.5 * IQR

print("\nLímite inferior:", limite_inferior)
print("Límite superior:", limite_superior)

outliers = datos[(datos["gasto_promedio"] < limite_inferior) | (datos["gasto_promedio"] > limite_superior)]

print("\nValores atípicos detectados:")
print(outliers)

# Reemplazo del outlier por la mediana
mediana_gasto = datos.loc[datos["gasto_promedio"] <= limite_superior, "gasto_promedio"].median()
datos.loc[datos["gasto_promedio"] > limite_superior, "gasto_promedio"] = mediana_gasto

plt.figure(figsize=(8, 4))
sns.boxplot(x=datos["gasto_promedio"])
plt.title("Boxplot de gasto promedio después de tratar outliers")
plt.xlabel("Gasto promedio")
plt.show()

# ============================================================
# 8. TRANSFORMACIÓN DE VARIABLES CATEGÓRICAS
# ============================================================

# En esta etapa se convierten las variables categóricas en formatos numéricos
# para que puedan ser utilizadas por los algoritmos de machine learning.

# ------------------------------------------------------------
# 1. Codificación ordinal de la variable satisfacción
# ------------------------------------------------------------

# La variable "satisfaccion" tiene un orden natural:
# Bajo < Medio < Alto

# Se asignan valores numéricos respetando ese orden:
# Bajo = 1, Medio = 2, Alto = 3

mapa_satisfaccion = {
    "Bajo": 1,
    "Medio": 2,
    "Alto": 3
}

datos["satisfaccion_codificada"] = datos["satisfaccion"].map(mapa_satisfaccion)

# Esta transformación permite representar una variable cualitativa ordinal
# como una variable numérica manteniendo su jerarquía.

# ------------------------------------------------------------
# 2. One-hot encoding para canal de compra
# ------------------------------------------------------------

# La variable "canal_compra" es categórica nominal (no tiene orden),
# por lo que no se puede asignar un valor numérico directo sin introducir sesgo.

# Se aplica One-Hot Encoding para crear columnas binarias:
# - canal_compra_Online
# - canal_compra_Tienda
# - canal_compra_Mixto

datos_transformados = pd.get_dummies(
    datos,
    columns=["canal_compra"],
    drop_first=False
)

# Cada nueva columna toma el valor:
# 1 (True) si el cliente pertenece a ese canal
# 0 (False) si no pertenece

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# El dataset resultante contiene ahora variables numéricas y binarias,
# lo que permite su uso directo en modelos de machine learning
# como árboles de decisión, regresión logística o clustering.

# La transformación conserva la información original:
# - satisfacción mantiene su orden lógico
# - canal de compra se representa sin imponer jerarquías artificiales

# Esto mejora la calidad del modelado y evita interpretaciones incorrectas
# por parte de los algoritmos.

# ============================================================
# 9. SELECCIÓN DE VARIABLES PARA EL MODELO
# ============================================================

# En esta etapa se definen las variables que serán utilizadas
# para entrenar el modelo de machine learning.

# ------------------------------------------------------------
# Variables predictoras (X)
# ------------------------------------------------------------

# Se seleccionan variables que representan el comportamiento del cliente:
# - edad: información demográfica
# - ingreso_mensual: capacidad económica
# - frecuencia_compra: hábito de consumo
# - gasto_promedio: nivel de consumo
# - satisfaccion_codificada: nivel de satisfacción del cliente
# - canal_compra_*: canal utilizado para realizar compras

variables_modelo = [
    "edad",
    "ingreso_mensual",
    "frecuencia_compra",
    "gasto_promedio",
    "satisfaccion_codificada",
    "canal_compra_Mixto",
    "canal_compra_Online",
    "canal_compra_Tienda"
]

# Matriz de características (features)
X = datos_transformados[variables_modelo]

# ------------------------------------------------------------
# Variable objetivo (y)
# ------------------------------------------------------------

# La variable "compra_alta" indica si el cliente pertenece a la categoría
# de alta compra (1) o no (0), y es la variable que el modelo debe predecir.

y = datos_transformados["compra_alta"]

# ------------------------------------------------------------
# Justificación de la selección
# ------------------------------------------------------------

# Las variables seleccionadas combinan información demográfica,
# económica, conductual y de experiencia del cliente.

# Esto permite al modelo aprender patrones más completos sobre
# qué factores influyen en una compra alta.

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# X contiene las variables predictoras utilizadas para el entrenamiento.
# y contiene la variable objetivo que el modelo intentará predecir.

# Esta separación es fundamental para cualquier proceso de aprendizaje supervisado.

print("\nVariables predictoras:")

print(X.head())

print("\nVariable objetivo:")

print(y.head())

# ============================================================
# 10. NORMALIZACIÓN DE VARIABLES
# ============================================================

# En esta etapa se realiza la estandarización de las variables predictoras
# para que todas tengan la misma escala numérica.

# ------------------------------------------------------------
# ¿Por qué es necesario?
# ------------------------------------------------------------

# Las variables del dataset tienen unidades y rangos diferentes:
# - edad: valores entre ~18 y 69
# - ingreso_mensual: miles de unidades
# - frecuencia_compra: valores pequeños
# - gasto_promedio: valores intermedios

# Si no se normalizan, las variables con valores más grandes
# pueden dominar el modelo y sesgar los resultados.

# ------------------------------------------------------------
# Método utilizado: StandardScaler
# ------------------------------------------------------------

# StandardScaler aplica la estandarización Z-score:
# cada valor se transforma restando la media y dividiendo por la desviación estándar.

# Esto produce variables con:
# - media ≈ 0
# - desviación estándar ≈ 1

escalador = StandardScaler()
X_escalado = escalador.fit_transform(X)

# Se convierte el resultado en DataFrame para mantener interpretabilidad
X_escalado = pd.DataFrame(X_escalado, columns=variables_modelo)

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# Los datos ahora están en una escala común, lo que permite que
# algoritmos como:
# - regresión logística
# - k-means
# - máquinas de soporte vectorial
# - redes neuronales

# funcionen correctamente sin que una variable tenga más peso
# solo por su magnitud numérica.

# Esto mejora la estabilidad del modelo y la calidad de las predicciones.

print("\nDatos normalizados:")
print(X_escalado.head())

# ============================================================
# 11. DIVISIÓN DE DATOS EN ENTRENAMIENTO Y PRUEBA
# ============================================================

# En esta etapa se separa el dataset en dos subconjuntos:
# uno para entrenar el modelo y otro para evaluarlo.

# ------------------------------------------------------------
# ¿Por qué es necesario?
# ------------------------------------------------------------

# Si se entrenara y evaluara el modelo con los mismos datos,
# no se podría medir su capacidad real de generalización.
# El modelo podría simplemente "memorizar" los datos (overfitting).

# ------------------------------------------------------------
# División realizada
# ------------------------------------------------------------

# - Conjunto de entrenamiento (train): 75% de los datos
#   Se utiliza para ajustar los parámetros del modelo.

# - Conjunto de prueba (test): 25% de los datos
#   Se utiliza para evaluar el desempeño del modelo en datos no vistos.

# ------------------------------------------------------------
# Parámetros utilizados
# ------------------------------------------------------------

# test_size=0.25
# → define que el 25% de los datos se reservan para prueba.

# random_state=42
# → asegura reproducibilidad del experimento (mismo split siempre).

# stratify=y
# → mantiene la misma proporción de clases (0 y 1) en train y test,
# evitando desbalance entre conjuntos.

X_train, X_test, y_train, y_test = train_test_split(
    X_escalado,
    y,
    test_size=0.25,
    random_state=42,
    stratify=y
)

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# Se obtienen dos conjuntos:
# - X_train / y_train → usados para entrenar el modelo
# - X_test / y_test → usados para evaluar su rendimiento

# Esto permite una evaluación más realista y confiable
# del comportamiento del modelo en datos nuevos.

print("\nTamaño del conjunto de entrenamiento:")
print(X_train.shape)

print("\nTamaño del conjunto de prueba:")
print(X_test.shape)

# ============================================================
# 12. MODELO DE CLASIFICACIÓN: ÁRBOL DE DECISIÓN
# ============================================================

# En esta etapa se entrena un modelo de clasificación supervisada
# utilizando un Árbol de Decisión.

# ------------------------------------------------------------
# ¿Qué es un árbol de decisión?
# ------------------------------------------------------------

# Es un algoritmo que divide los datos en ramas según reglas
# basadas en las variables predictoras.
# Cada división busca reducir la impureza y mejorar la separación
# entre clases (en este caso, compra alta vs no compra alta).

# ------------------------------------------------------------
# Configuración del modelo
# ------------------------------------------------------------

modelo_arbol = DecisionTreeClassifier(
    max_depth=4,      # limita la profundidad del árbol para evitar overfitting
    random_state=42   # asegura resultados reproducibles
)

# ------------------------------------------------------------
# Entrenamiento del modelo
# ------------------------------------------------------------

# El modelo aprende patrones a partir del conjunto de entrenamiento
modelo_arbol.fit(X_train, y_train)

# ------------------------------------------------------------
# Predicción
# ------------------------------------------------------------

# Se generan predicciones usando el conjunto de prueba
predicciones = modelo_arbol.predict(X_test)

# ------------------------------------------------------------
# RESULTADO
# ------------------------------------------------------------

# El modelo ha sido entrenado correctamente y ya puede ser utilizado
# para predecir si un cliente pertenece a la categoría de compra alta
# en función de sus características.

# La limitación de profundidad (max_depth=4) ayuda a mantener el modelo
# interpretable y reduce el riesgo de sobreajuste.


print("\nModelo de árbol de decisión entrenado correctamente")

# ============================================================
# 13. EVALUACIÓN DEL MODELO DE CLASIFICACIÓN
# ============================================================

# En esta etapa se evalúa el desempeño del árbol de decisión
# utilizando diferentes métricas de clasificación.

# ------------------------------------------------------------
# Métricas utilizadas
# ------------------------------------------------------------

# Accuracy:
# Mide el porcentaje total de predicciones correctas
# (tanto clase 0 como clase 1).

# Precision:
# De todos los clientes predichos como "compra alta (1)",
# qué proporción realmente lo era.
# Es importante cuando queremos evitar falsos positivos.

# Recall:
# De todos los clientes que realmente eran "compra alta (1)",
# qué proporción fue correctamente identificada.
# Es importante cuando queremos evitar perder clientes valiosos.

# ------------------------------------------------------------
# Cálculo de métricas
# ------------------------------------------------------------

accuracy = accuracy_score(y_test, predicciones)
precision = precision_score(y_test, predicciones)
recall = recall_score(y_test, predicciones)

print("\nRESULTADOS DEL MODELO DE CLASIFICACIÓN")
print("Accuracy:", round(accuracy, 3))
print("Precision:", round(precision, 3))
print("Recall:", round(recall, 3))
print("\n")


# ------------------------------------------------------------
# RESULTADOS OBTENIDOS
# ------------------------------------------------------------

# Accuracy: 0.500
# → El modelo acierta el 50% de los casos, lo cual indica
#   un rendimiento bajo (similar a una predicción aleatoria).

# Precision: 0.455
# → Solo el 45.5% de los clientes predichos como compra alta
#   realmente pertenecen a esa categoría.

# Recall: 0.588
# → El modelo logra identificar el 58.8% de los clientes
#   que realmente son de compra alta.

# ------------------------------------------------------------
# Reporte de clasificación
# ------------------------------------------------------------

# Clase 0 (no compra alta):
# - Precision: 0.56
# - Recall: 0.43
# → El modelo identifica mejor esta clase en precisión,
#   pero pierde varios casos reales (bajo recall).

# Clase 1 (compra alta):
# - Precision: 0.45
# - Recall: 0.59
# → Detecta más clientes de compra alta, pero con más errores.

# ------------------------------------------------------------
# MATRIZ DE CONFUSIÓN
# ------------------------------------------------------------

matriz = confusion_matrix(y_test, predicciones)

# La matriz permite visualizar:
# - Verdaderos positivos
# - Verdaderos negativos
# - Falsos positivos
# - Falsos negativos

# Se representa con un heatmap para facilitar su interpretación.

plt.figure(figsize=(6, 4))
sns.heatmap(matriz, annot=True, fmt="d", cmap="Blues")
plt.title("Matriz de confusión")
plt.xlabel("Predicción del modelo")
plt.ylabel("Valor real")
plt.show()

# ------------------------------------------------------------
# CONCLUSIÓN
# ------------------------------------------------------------

# El modelo presenta un desempeño limitado, con accuracy del 50%.
# Esto indica que aún no es suficientemente robusto para producción
# y requiere mejoras en variables, balanceo o ajuste de hiperparámetros.


print("\nReporte de clasificación:")
print(classification_report(y_test, predicciones))

# ============================================================
# 14. VISUALIZACIÓN DEL ÁRBOL DE DECISIÓN
# ============================================================

# En esta etapa se genera una representación gráfica del modelo
# de árbol de decisión ya entrenado.

# ------------------------------------------------------------
# ¿Para qué sirve esta visualización?
# ------------------------------------------------------------

# El diagrama del árbol permite interpretar cómo el modelo
# toma decisiones paso a paso.

# Cada nodo representa una condición sobre una variable
# (por ejemplo: gasto_promedio <= cierto valor),
# y cada rama representa el resultado de esa decisión.

# ------------------------------------------------------------
# Elementos del gráfico
# ------------------------------------------------------------

# - feature_names:
#   Muestra los nombres de las variables utilizadas en cada división.

# - class_names:
#   Indica las clases objetivo:
#   "Compra baja" y "Compra alta".

# - filled=True:
#   Colorea los nodos según la clase dominante,
#   facilitando la interpretación visual.

# - rounded=True:
#   Mejora la estética del árbol con nodos redondeados.

# ------------------------------------------------------------
# INTERPRETACIÓN
# ------------------------------------------------------------

# El árbol permite identificar:
# - Qué variables tienen mayor impacto en la decisión.
# - En qué orden el modelo segmenta a los clientes.
# - Qué reglas utiliza para clasificar "compra alta".

# Esto hace que el modelo sea interpretable,
# a diferencia de algoritmos más complejos como redes neuronales.

plt.figure(figsize=(18, 8))

plot_tree(
    modelo_arbol,
    feature_names=variables_modelo,
    class_names=["Compra baja", "Compra alta"],
    filled=True,
    rounded=True
)

plt.title("Árbol de decisión para clasificar clientes")
plt.show()

# ============================================================
# 15. IMPORTANCIA DE VARIABLES
# ============================================================

# En esta etapa se analiza qué variables tienen mayor influencia
# en las decisiones del modelo de árbol de decisión.

# ------------------------------------------------------------
# ¿Qué es la importancia de variables?
# ------------------------------------------------------------

# Es una métrica interna del modelo que indica cuánto contribuye
# cada variable a reducir la impureza en el árbol.

# En otras palabras:
# - Variables con mayor importancia influyen más en la predicción.
# - Variables con menor importancia aportan menos información útil.

# ------------------------------------------------------------
# Cálculo de importancias
# ------------------------------------------------------------

importancias = pd.DataFrame({
    "Variable": variables_modelo,
    "Importancia": modelo_arbol.feature_importances_
}).sort_values(by="Importancia", ascending=False)

# ------------------------------------------------------------
# RESULTADO TABULAR
# ------------------------------------------------------------

# Se ordenan las variables de mayor a menor importancia
# para identificar los factores más relevantes en la predicción
# de "compra alta".

print("\nImportancia de variables en el modelo:")
print(importancias)

# ------------------------------------------------------------
