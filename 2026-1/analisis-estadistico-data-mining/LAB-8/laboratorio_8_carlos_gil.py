# 5. LIMPIEZA DE DATOS
# ============================================================

# Corrección de edad negativa
# Regla de negocio: la edad debe estar entre 18 y 70 años.
# Si aparece una edad negativa, se reemplaza por la mediana de edades válidas.

mediana_edad = datos.loc[datos["edad"] >= 18, "edad"].median()
